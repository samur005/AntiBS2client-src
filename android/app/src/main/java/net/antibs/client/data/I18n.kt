/**
 * 2.0.30: in-app strings for Android + Windows. [tag] is a concrete BCP-47 language
 * (never «system»); call [AppLang.resolve] first. Fallback for missing keys: English.
 * Resource `strings.xml` / AppCompat locales mirror the same tags (no fa).
 */
object I18n {
    /** Concrete language tag currently used for [t]. */
    var tag: String by mutableStateOf("ru")
        private set

    fun use(resolved: String) {
        val t = AppLang.resolve(resolved)
        if (tag != t) tag = t
    }

    fun t(key: String): String {
        val m = tables[tag] ?: T_EN
        return m[key] ?: T_EN[key] ?: key
    }

    fun t(key: String, vararg args: Any): String {
        var s = t(key)
        args.forEachIndexed { i, a -> s = s.replace("{" + i + "}", a.toString()) }
        return s
    }

    fun daysWord(n: Int): String {
        val n10 = n % 10; val n100 = n % 100
        // Slavic-style for ru/uk; otherwise day_many
        return when (tag) {
            "ru", "uk" -> when {
                n10 == 1 && n100 != 11 -> t("day_one")
                n10 in 2..4 && n100 !in 12..14 -> t("day_few")
                else -> t("day_many")
            }
            else -> if (n == 1) t("day_one") else t("day_many")
        }
    }

